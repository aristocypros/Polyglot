//! AES-256-GCM wallet seed wrapping and unwrapping with AEAD Associated Authenticated Data (AAD).
//!
//! Implements Task 08 of the generic PKCS#11 backend (Section 4 and Section 8 of `Specs.md`):
//! - KEK lookup by label (`"kek-v1"`) via `C_FindObjectsInit` / `C_FindObjects` / `C_FindObjectsFinal`
//!   and strict verification of KEK attributes via `C_GetAttributeValue`:
//!   `CKA_CLASS = CKO_SECRET_KEY`, `CKA_KEY_TYPE = CKK_AES`, `CKA_EXTRACTABLE = false`,
//!   `CKA_SENSITIVE = true`, `CKA_ENCRYPT = true`, `CKA_DECRYPT = true` (plus 256-bit `CKA_VALUE_LEN`
//!   and encrypt/decrypt-only usage flags when reported by the token).
//! - [`wrap_seed`]: requests a fresh 12-byte (96-bit) IV from `C_GenerateRandom`, encrypts the
//!   64-byte wallet seed under the KEK using `CKM_AES_GCM` with the caller-supplied canonical AAD
//!   (`wallet_id | scheme | curve | seed_version | kek_label`) and a 128-bit authentication tag,
//!   and formats the 92-byte stored blob as `IV (12B) || ciphertext (64B) || tag (16B)`.
//! - [`unwrap_seed`]: parses the 92-byte wrapped blob, decrypts via `C_Decrypt` with `CKM_AES_GCM`
//!   and the caller-supplied AAD directly into a [`Zeroizing<[u8; 64]>`] buffer, and fails closed
//!   with zero partial output on tampered IV/ciphertext/tag, wrong AAD, swapped wallet blob,
//!   malformed/truncated blob, or missing/invalid KEK.

use cryptoki::mechanism::aead::GcmParams;
use cryptoki::mechanism::Mechanism;
use cryptoki::object::{Attribute, AttributeType, KeyType, ObjectClass, ObjectHandle};
use cryptoki::types::Ulong;
use zeroize::Zeroizing;

use crate::backend::{
    BackendError, AAD_DELIMITER, AES_GCM_IV_LEN, AES_GCM_TAG_LEN, WALLET_SEED_LEN,
    WRAPPED_SEED_LEN,
};
use crate::pkcs11session::{map_pkcs11_err, Pkcs11Session};

/// Authentication tag length in bits for `CKM_AES_GCM` (`128` bits = `16` bytes).
pub const AES_GCM_TAG_BITS: u64 = (AES_GCM_TAG_LEN * 8) as u64;

/// Expected byte length of the AES-256 Key Encryption Key (`256` bits = `32` bytes).
pub const AES_256_KEY_LEN: usize = 32;

/// Expected byte length of the raw `C_Encrypt` output for a 64-byte seed under `CKM_AES_GCM`:
/// `ciphertext (64B) || tag (16B)` = `80` bytes.
pub const AES_GCM_CIPHERTEXT_AND_TAG_LEN: usize = WALLET_SEED_LEN + AES_GCM_TAG_LEN;

/// Parsed representation of the 92-byte wrapped wallet seed blob stored in `app.wallets.wrapped_seed`.
///
/// Exact byte layout (`92` bytes total = [`WRAPPED_SEED_LEN`]):
/// - Bytes `0..12` (`12` bytes, [`AES_GCM_IV_LEN`]): 96-bit AES-GCM initialization vector (IV)
/// - Bytes `12..76` (`64` bytes, [`WALLET_SEED_LEN`]): encrypted wallet seed ciphertext
/// - Bytes `76..92` (`16` bytes, [`AES_GCM_TAG_LEN`]): 128-bit AES-GCM authentication tag
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct WrappedSeedBlob {
    /// 12-byte (96-bit) initialization vector generated by `C_GenerateRandom`.
    pub iv: [u8; AES_GCM_IV_LEN],
    /// 64-byte AES-256-GCM ciphertext of the wallet seed.
    pub ciphertext: [u8; WALLET_SEED_LEN],
    /// 16-byte (128-bit) AES-256-GCM authentication tag.
    pub tag: [u8; AES_GCM_TAG_LEN],
}

impl WrappedSeedBlob {
    /// Constructs a [`WrappedSeedBlob`] from its `iv` (12B), `ciphertext` (64B), and `tag` (16B) parts.
    pub const fn new(
        iv: [u8; AES_GCM_IV_LEN],
        ciphertext: [u8; WALLET_SEED_LEN],
        tag: [u8; AES_GCM_TAG_LEN],
    ) -> Self {
        Self {
            iv,
            ciphertext,
            tag,
        }
    }

    /// Constructs a [`WrappedSeedBlob`] from a 12-byte `iv` and the 80-byte `ciphertext || tag`
    /// output returned by PKCS#11 `C_Encrypt` (`CKM_AES_GCM`).
    pub fn from_iv_and_encrypted(
        iv: &[u8; AES_GCM_IV_LEN],
        ciphertext_and_tag: &[u8],
    ) -> Result<Self, BackendError> {
        if ciphertext_and_tag.len() != AES_GCM_CIPHERTEXT_AND_TAG_LEN {
            return Err(BackendError::WrapFailed(format!(
                "CKM_AES_GCM C_Encrypt returned {} bytes; expected {} bytes ({}B ciphertext + {}B tag)",
                ciphertext_and_tag.len(),
                AES_GCM_CIPHERTEXT_AND_TAG_LEN,
                WALLET_SEED_LEN,
                AES_GCM_TAG_LEN
            )));
        }

        let mut ciphertext = [0u8; WALLET_SEED_LEN];
        ciphertext.copy_from_slice(&ciphertext_and_tag[..WALLET_SEED_LEN]);

        let mut tag = [0u8; AES_GCM_TAG_LEN];
        tag.copy_from_slice(&ciphertext_and_tag[WALLET_SEED_LEN..]);

        Ok(Self {
            iv: *iv,
            ciphertext,
            tag,
        })
    }

    /// Parses a 92-byte (`WRAPPED_SEED_LEN`) slice into a [`WrappedSeedBlob`].
    ///
    /// Rejects empty, truncated, or oversized slices with [`BackendError::InvalidWrappedSeed`].
    pub fn from_slice(blob: &[u8]) -> Result<Self, BackendError> {
        if blob.len() != WRAPPED_SEED_LEN {
            return Err(BackendError::InvalidWrappedSeed(format!(
                "expected {WRAPPED_SEED_LEN}-byte wrapped seed blob (12B IV + 64B ciphertext + 16B tag), got {} bytes",
                blob.len()
            )));
        }

        let mut iv = [0u8; AES_GCM_IV_LEN];
        iv.copy_from_slice(&blob[..AES_GCM_IV_LEN]);

        let mut ciphertext = [0u8; WALLET_SEED_LEN];
        ciphertext.copy_from_slice(&blob[AES_GCM_IV_LEN..AES_GCM_IV_LEN + WALLET_SEED_LEN]);

        let mut tag = [0u8; AES_GCM_TAG_LEN];
        tag.copy_from_slice(&blob[AES_GCM_IV_LEN + WALLET_SEED_LEN..]);

        Ok(Self {
            iv,
            ciphertext,
            tag,
        })
    }

    /// Returns a reference to the 12-byte IV.
    pub const fn iv(&self) -> &[u8; AES_GCM_IV_LEN] {
        &self.iv
    }

    /// Returns a reference to the 64-byte ciphertext.
    pub const fn ciphertext(&self) -> &[u8; WALLET_SEED_LEN] {
        &self.ciphertext
    }

    /// Returns a reference to the 16-byte authentication tag.
    pub const fn tag(&self) -> &[u8; AES_GCM_TAG_LEN] {
        &self.tag
    }

    /// Concatenates `ciphertext (64B) || tag (16B)` into the 80-byte buffer expected by
    /// PKCS#11 `C_Decrypt` (`CKM_AES_GCM`).
    pub fn ciphertext_and_tag(&self) -> [u8; AES_GCM_CIPHERTEXT_AND_TAG_LEN] {
        let mut out = [0u8; AES_GCM_CIPHERTEXT_AND_TAG_LEN];
        out[..WALLET_SEED_LEN].copy_from_slice(&self.ciphertext);
        out[WALLET_SEED_LEN..].copy_from_slice(&self.tag);
        out
    }

    /// Serializes this [`WrappedSeedBlob`] to its canonical 92-byte array:
    /// `IV (12B) || ciphertext (64B) || tag (16B)`.
    pub fn to_bytes(&self) -> [u8; WRAPPED_SEED_LEN] {
        let mut out = [0u8; WRAPPED_SEED_LEN];
        out[..AES_GCM_IV_LEN].copy_from_slice(&self.iv);
        out[AES_GCM_IV_LEN..AES_GCM_IV_LEN + WALLET_SEED_LEN].copy_from_slice(&self.ciphertext);
        out[AES_GCM_IV_LEN + WALLET_SEED_LEN..].copy_from_slice(&self.tag);
        out
    }

    /// Serializes this [`WrappedSeedBlob`] to a 92-byte [`Vec<u8>`]:
    /// `IV (12B) || ciphertext (64B) || tag (16B)`.
    pub fn to_vec(&self) -> Vec<u8> {
        self.to_bytes().to_vec()
    }
}

/// Parses a 92-byte wrapped seed slice (`IV (12B) || ciphertext (64B) || tag (16B)`) into a
/// [`WrappedSeedBlob`].
pub fn parse_wrapped_seed(blob: &[u8]) -> Result<WrappedSeedBlob, BackendError> {
    WrappedSeedBlob::from_slice(blob)
}

/// Verified PKCS#11 metadata for the HSM Key Encryption Key (KEK).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct KekMetadata {
    /// PKCS#11 object handle of the KEK on the token.
    pub handle: ObjectHandle,
    /// KEK label (`CKA_LABEL`, e.g., `"kek-v1"`).
    pub label: String,
    /// Object class (`CKA_CLASS`, verified to be `CKO_SECRET_KEY`).
    pub class: ObjectClass,
    /// Key type (`CKA_KEY_TYPE`, verified to be `CKK_AES`).
    pub key_type: KeyType,
    /// Whether the key is extractable (`CKA_EXTRACTABLE`, verified to be `false`).
    pub extractable: bool,
    /// Whether the key is sensitive (`CKA_SENSITIVE`, verified to be `true`).
    pub sensitive: bool,
    /// Whether the key supports encryption (`CKA_ENCRYPT`, verified to be `true`).
    pub encrypt: bool,
    /// Whether the key supports decryption (`CKA_DECRYPT`, verified to be `true`).
    pub decrypt: bool,
    /// Optional key length in bytes (`CKA_VALUE_LEN`, verified to be `32` if reported by the token).
    pub value_len: Option<usize>,
}

/// Validates a KEK label string before querying PKCS#11.
pub fn validate_kek_label(label: &str) -> Result<(), BackendError> {
    if label.is_empty() {
        return Err(BackendError::InvalidKekAttributes(
            "KEK label must not be empty".to_string(),
        ));
    }
    if label.contains(AAD_DELIMITER) || label.contains('\0') {
        return Err(BackendError::InvalidKekAttributes(
            "KEK label must not contain '|' or NUL bytes".to_string(),
        ));
    }
    Ok(())
}

/// Verifies that the PKCS#11 object at `handle` satisfies all security and usage attributes
/// required for the HSM AES-256 KEK:
/// - `CKA_CLASS == CKO_SECRET_KEY`
/// - `CKA_KEY_TYPE == CKK_AES`
/// - `CKA_EXTRACTABLE == false`
/// - `CKA_SENSITIVE == true`
/// - `CKA_ENCRYPT == true`
/// - `CKA_DECRYPT == true`
/// - If `CKA_VALUE_LEN` is reported, `CKA_VALUE_LEN == 32` (256 bits)
/// - If `CKA_WRAP`, `CKA_UNWRAP`, `CKA_SIGN`, `CKA_VERIFY`, or `CKA_DERIVE` are reported,
///   each must be `false` (encrypt and decrypt only).
pub fn verify_kek_attributes(
    session: &Pkcs11Session,
    handle: ObjectHandle,
    label: &str,
) -> Result<KekMetadata, BackendError> {
    const QUERIED_ATTRS: &[AttributeType] = &[
        AttributeType::Class,
        AttributeType::KeyType,
        AttributeType::Extractable,
        AttributeType::Sensitive,
        AttributeType::Encrypt,
        AttributeType::Decrypt,
        AttributeType::ValueLen,
        AttributeType::Wrap,
        AttributeType::Unwrap,
        AttributeType::Sign,
        AttributeType::Verify,
        AttributeType::Derive,
    ];

    let attributes = session
        .raw()
        .get_attributes(handle, QUERIED_ATTRS)
        .map_err(|err| {
            BackendError::InvalidKekAttributes(format!(
                "failed to query attributes for KEK '{label}': {err}"
            ))
        })?;

    let mut class: Option<ObjectClass> = None;
    let mut key_type: Option<KeyType> = None;
    let mut extractable: Option<bool> = None;
    let mut sensitive: Option<bool> = None;
    let mut encrypt: Option<bool> = None;
    let mut decrypt: Option<bool> = None;
    let mut value_len: Option<usize> = None;
    let mut wrap_flag: Option<bool> = None;
    let mut unwrap_flag: Option<bool> = None;
    let mut sign_flag: Option<bool> = None;
    let mut verify_flag: Option<bool> = None;
    let mut derive_flag: Option<bool> = None;

    for attr in attributes {
        match attr {
            Attribute::Class(v) => class = Some(v),
            Attribute::KeyType(v) => key_type = Some(v),
            Attribute::Extractable(v) => extractable = Some(v),
            Attribute::Sensitive(v) => sensitive = Some(v),
            Attribute::Encrypt(v) => encrypt = Some(v),
            Attribute::Decrypt(v) => decrypt = Some(v),
            Attribute::ValueLen(v) => value_len = Some(usize::from(v)),
            Attribute::Wrap(v) => wrap_flag = Some(v),
            Attribute::Unwrap(v) => unwrap_flag = Some(v),
            Attribute::Sign(v) => sign_flag = Some(v),
            Attribute::Verify(v) => verify_flag = Some(v),
            Attribute::Derive(v) => derive_flag = Some(v),
            _ => {}
        }
    }

    // 1. CKA_CLASS == CKO_SECRET_KEY
    let actual_class = class.ok_or_else(|| {
        BackendError::InvalidKekAttributes(format!(
            "KEK '{label}' is missing required attribute CKA_CLASS"
        ))
    })?;
    if actual_class != ObjectClass::SECRET_KEY {
        return Err(BackendError::InvalidKekAttributes(format!(
            "KEK '{label}' has invalid CKA_CLASS: expected CKO_SECRET_KEY, got {actual_class}"
        )));
    }

    // 2. CKA_KEY_TYPE == CKK_AES
    let actual_key_type = key_type.ok_or_else(|| {
        BackendError::InvalidKekAttributes(format!(
            "KEK '{label}' is missing required attribute CKA_KEY_TYPE"
        ))
    })?;
    if actual_key_type != KeyType::AES {
        return Err(BackendError::InvalidKekAttributes(format!(
            "KEK '{label}' has invalid CKA_KEY_TYPE: expected CKK_AES, got {actual_key_type}"
        )));
    }

    // 3. CKA_EXTRACTABLE == false
    let actual_extractable = extractable.ok_or_else(|| {
        BackendError::InvalidKekAttributes(format!(
            "KEK '{label}' is missing required attribute CKA_EXTRACTABLE"
        ))
    })?;
    if actual_extractable {
        return Err(BackendError::InvalidKekAttributes(format!(
            "KEK '{label}' has CKA_EXTRACTABLE=true; KEK must be non-extractable (CKA_EXTRACTABLE=false)"
        )));
    }

    // 4. CKA_SENSITIVE == true
    let actual_sensitive = sensitive.ok_or_else(|| {
        BackendError::InvalidKekAttributes(format!(
            "KEK '{label}' is missing required attribute CKA_SENSITIVE"
        ))
    })?;
    if !actual_sensitive {
        return Err(BackendError::InvalidKekAttributes(format!(
            "KEK '{label}' has CKA_SENSITIVE=false; KEK must be sensitive (CKA_SENSITIVE=true)"
        )));
    }

    // 5. CKA_ENCRYPT == true
    let actual_encrypt = encrypt.ok_or_else(|| {
        BackendError::InvalidKekAttributes(format!(
            "KEK '{label}' is missing required attribute CKA_ENCRYPT"
        ))
    })?;
    if !actual_encrypt {
        return Err(BackendError::InvalidKekAttributes(format!(
            "KEK '{label}' has CKA_ENCRYPT=false; KEK must allow encryption (CKA_ENCRYPT=true)"
        )));
    }

    // 6. CKA_DECRYPT == true
    let actual_decrypt = decrypt.ok_or_else(|| {
        BackendError::InvalidKekAttributes(format!(
            "KEK '{label}' is missing required attribute CKA_DECRYPT"
        ))
    })?;
    if !actual_decrypt {
        return Err(BackendError::InvalidKekAttributes(format!(
            "KEK '{label}' has CKA_DECRYPT=false; KEK must allow decryption (CKA_DECRYPT=true)"
        )));
    }

    // 7. If CKA_VALUE_LEN is available, verify it is 32 bytes (256 bits)
    if let Some(len) = value_len {
        if len != AES_256_KEY_LEN {
            return Err(BackendError::InvalidKekAttributes(format!(
                "KEK '{label}' has invalid CKA_VALUE_LEN={len}; expected {AES_256_KEY_LEN} bytes (AES-256)"
            )));
        }
    }

    // 8. Verify encrypt/decrypt-only restriction if extra usage flags are reported
    for (attr_name, flag_val) in [
        ("CKA_WRAP", wrap_flag),
        ("CKA_UNWRAP", unwrap_flag),
        ("CKA_SIGN", sign_flag),
        ("CKA_VERIFY", verify_flag),
        ("CKA_DERIVE", derive_flag),
    ] {
        if flag_val == Some(true) {
            return Err(BackendError::InvalidKekAttributes(format!(
                "KEK '{label}' has {attr_name}=true; KEK must permit encrypt and decrypt only"
            )));
        }
    }

    Ok(KekMetadata {
        handle,
        label: label.to_string(),
        class: actual_class,
        key_type: actual_key_type,
        extractable: actual_extractable,
        sensitive: actual_sensitive,
        encrypt: actual_encrypt,
        decrypt: actual_decrypt,
        value_len,
    })
}

/// Locates the KEK object by `label` on `session` and validates all required KEK attributes.
///
/// - Returns [`BackendError::KekNotFound`] if no object with `CKA_LABEL == label` exists.
/// - Returns [`BackendError::InvalidKekAttributes`] if multiple objects share `label` or if any
///   required attribute (`CKA_CLASS=CKO_SECRET_KEY`, `CKA_KEY_TYPE=CKK_AES`, `CKA_EXTRACTABLE=false`,
///   `CKA_SENSITIVE=true`, `CKA_ENCRYPT=true`, `CKA_DECRYPT=true`) is missing or invalid.
pub fn find_and_validate_kek_by_label(
    session: &Pkcs11Session,
    label: &str,
) -> Result<KekMetadata, BackendError> {
    validate_kek_label(label)?;

    let search_template = [Attribute::Label(label.as_bytes().to_vec())];
    let handles = session
        .raw()
        .find_objects(&search_template)
        .map_err(|err| map_pkcs11_err("C_FindObjects (KEK lookup)", err))?;

    if handles.is_empty() {
        return Err(BackendError::KekNotFound(label.to_string()));
    }
    if handles.len() > 1 {
        return Err(BackendError::InvalidKekAttributes(format!(
            "expected exactly 1 KEK object with label '{label}', found {}",
            handles.len()
        )));
    }

    verify_kek_attributes(session, handles[0], label)
}

/// Locates and validates the KEK configured on `session` (`session.kek_label()`, e.g., `"kek-v1"`).
pub fn find_and_validate_kek(session: &Pkcs11Session) -> Result<KekMetadata, BackendError> {
    find_and_validate_kek_by_label(session, session.kek_label())
}

/// Locates the KEK by `label`, verifies its attributes, and returns its [`ObjectHandle`].
pub fn find_kek_by_label(
    session: &Pkcs11Session,
    label: &str,
) -> Result<ObjectHandle, BackendError> {
    Ok(find_and_validate_kek_by_label(session, label)?.handle)
}

/// Locates the KEK configured on `session` (`session.kek_label()`), verifies its attributes,
/// and returns its [`ObjectHandle`].
pub fn find_kek(session: &Pkcs11Session) -> Result<ObjectHandle, BackendError> {
    Ok(find_and_validate_kek(session)?.handle)
}

/// Wraps a 64-byte wallet `seed` under the HSM KEK identified by `kek_label` using `CKM_AES_GCM`
/// with a fresh 12-byte IV from `C_GenerateRandom`, the caller-supplied `aad`
/// (`wallet_id | scheme | curve | seed_version | kek_label`), and a 128-bit authentication tag.
///
/// Returns the 92-byte wrapped seed blob: `IV (12B) || ciphertext (64B) || tag (16B)`.
pub fn wrap_seed_with_kek_label(
    session: &Pkcs11Session,
    kek_label: &str,
    seed: &[u8],
    aad: &[u8],
) -> Result<Vec<u8>, BackendError> {
    if seed.len() != WALLET_SEED_LEN {
        return Err(BackendError::WrapFailed(format!(
            "wallet seed length must be {WALLET_SEED_LEN} bytes, got {} bytes",
            seed.len()
        )));
    }
    if aad.is_empty() {
        return Err(BackendError::InvalidAad(
            "AEAD associated data (AAD) must not be empty when wrapping a wallet seed".to_string(),
        ));
    }

    // 1. Locate KEK by label and verify attributes before encrypting
    let kek = find_and_validate_kek_by_label(session, kek_label)?;

    // 2. Request a fresh 12-byte (96-bit) IV from C_GenerateRandom
    let mut iv = session
        .generate_aes_gcm_iv()
        .map_err(|err| BackendError::WrapFailed(format!("failed to generate 12B AES-GCM IV: {err}")))?;

    if iv.iter().all(|&b| b == 0) {
        return Err(BackendError::WrapFailed(
            "C_GenerateRandom returned an all-zero 12-byte AES-GCM IV".to_string(),
        ));
    }

    // 3. Encrypt the 64-byte seed under the KEK with CKM_AES_GCM (128-bit tag + AAD)
    let ciphertext_and_tag = {
        let gcm_params = GcmParams::new(
            iv.as_mut_slice(),
            aad,
            Ulong::from(AES_GCM_TAG_BITS),
        )
        .map_err(|err| {
            BackendError::WrapFailed(format!("failed to construct CK_GCM_PARAMS: {err}"))
        })?;
        let mechanism = Mechanism::AesGcm(gcm_params);

        session
            .raw()
            .encrypt(&mechanism, kek.handle, seed)
            .map_err(|err| {
                BackendError::WrapFailed(format!("C_Encrypt (CKM_AES_GCM) failed: {err}"))
            })?
    };

    // 4. Format as IV (12B) || ciphertext (64B) || tag (16B) (92 bytes total)
    let blob = WrappedSeedBlob::from_iv_and_encrypted(&iv, &ciphertext_and_tag)?;
    Ok(blob.to_vec())
}

/// Wraps a 64-byte wallet `seed` under the session's configured KEK (`session.kek_label()`,
/// default `"kek-v1"`) using `CKM_AES_GCM` with a fresh 12-byte IV from `C_GenerateRandom`,
/// the caller-supplied `aad`, and a 128-bit authentication tag.
///
/// Returns the 92-byte wrapped seed blob: `IV (12B) || ciphertext (64B) || tag (16B)`.
pub fn wrap_seed(
    session: &Pkcs11Session,
    seed: &[u8],
    aad: &[u8],
) -> Result<Vec<u8>, BackendError> {
    wrap_seed_with_kek_label(session, session.kek_label(), seed, aad)
}

/// Unwraps a 92-byte `wrapped` seed blob (`IV (12B) || ciphertext (64B) || tag (16B)`)
/// using `C_Decrypt` (`CKM_AES_GCM`) under the HSM KEK identified by `kek_label` and
/// the caller-supplied `aad`.
///
/// Outputs the decrypted 64-byte seed into a [`Zeroizing<[u8; WALLET_SEED_LEN]>`] buffer and
/// wipes all temporary buffers. Fails closed with zero partial output on:
/// - truncated, empty, or oversized `wrapped` blobs ([`BackendError::InvalidWrappedSeed`]),
/// - missing KEK ([`BackendError::KekNotFound`]) or invalid KEK attributes ([`BackendError::InvalidKekAttributes`]),
/// - tampered IV, tampered ciphertext, tampered tag, wrong AAD, or a blob from another wallet
///   ([`BackendError::UnwrapFailed`]).
pub fn unwrap_seed_with_kek_label(
    session: &Pkcs11Session,
    kek_label: &str,
    wrapped: &[u8],
    aad: &[u8],
) -> Result<Zeroizing<[u8; WALLET_SEED_LEN]>, BackendError> {
    // 1. Parse and validate the 92-byte blob layout (12B IV + 64B ciphertext + 16B tag)
    let blob = WrappedSeedBlob::from_slice(wrapped)?;

    if aad.is_empty() {
        return Err(BackendError::UnwrapFailed(
            "AEAD associated data (AAD) must not be empty when unwrapping a wallet seed"
                .to_string(),
        ));
    }

    // 2. Locate KEK by label and verify attributes before decrypting
    let kek = find_and_validate_kek_by_label(session, kek_label)?;

    // 3. Execute C_Decrypt with CKM_AES_GCM using the blob's 12B IV, caller's AAD, and 128-bit tag
    let mut iv_buf = Zeroizing::new(blob.iv);
    let ciphertext_and_tag = blob.ciphertext_and_tag();

    let mut decrypted_vec = Zeroizing::new({
        let gcm_params = GcmParams::new(
            iv_buf.as_mut_slice(),
            aad,
            Ulong::from(AES_GCM_TAG_BITS),
        )
        .map_err(|err| {
            BackendError::UnwrapFailed(format!("failed to construct CK_GCM_PARAMS: {err}"))
        })?;
        let mechanism = Mechanism::AesGcm(gcm_params);

        session
            .raw()
            .decrypt(&mechanism, kek.handle, &ciphertext_and_tag)
            .map_err(|err| {
                BackendError::UnwrapFailed(format!("C_Decrypt (CKM_AES_GCM) failed: {err}"))
            })?
    });

    if decrypted_vec.len() != WALLET_SEED_LEN {
        let actual_len = decrypted_vec.len();
        let cap = decrypted_vec.capacity();
        decrypted_vec.resize(cap, 0);
        return Err(BackendError::UnwrapFailed(format!(
            "C_Decrypt returned {actual_len} bytes; expected {WALLET_SEED_LEN} bytes"
        )));
    }

    // 4. Copy the 64-byte plaintext seed into a fixed-size Zeroizing<[u8; 64]> array and
    //    wipe the full heap capacity of the temporary Vec<u8>.
    let mut seed = Zeroizing::new([0u8; WALLET_SEED_LEN]);
    seed.copy_from_slice(&decrypted_vec);

    let cap = decrypted_vec.capacity();
    decrypted_vec.resize(cap, 0);
    drop(decrypted_vec);

    Ok(seed)
}

/// Unwraps a 92-byte `wrapped` seed blob (`IV (12B) || ciphertext (64B) || tag (16B)`)
/// using `C_Decrypt` (`CKM_AES_GCM`) under the session's configured KEK (`session.kek_label()`,
/// default `"kek-v1"`) and the caller-supplied `aad`.
///
/// Outputs the decrypted 64-byte seed into [`Zeroizing<[u8; WALLET_SEED_LEN]>`].
pub fn unwrap_seed(
    session: &Pkcs11Session,
    wrapped: &[u8],
    aad: &[u8],
) -> Result<Zeroizing<[u8; WALLET_SEED_LEN]>, BackendError> {
    unwrap_seed_with_kek_label(session, session.kek_label(), wrapped, aad)
}

