    #[test]
    fn test_wrapped_seed_blob_layout_and_parsing() {
        let mut iv = [0u8; AES_GCM_IV_LEN];
        for (i, b) in iv.iter_mut().enumerate() {
            *b = (i as u8) + 1;
        }
        let mut ciphertext = [0u8; WALLET_SEED_LEN];
        for (i, b) in ciphertext.iter_mut().enumerate() {
            *b = (i as u8) ^ 0xAA;
        }
        let mut tag = [0u8; AES_GCM_TAG_LEN];
        for (i, b) in tag.iter_mut().enumerate() {
            *b = (i as u8) ^ 0x55;
        }

        let blob = WrappedSeedBlob::new(iv, ciphertext, tag);
        let raw_bytes = blob.to_bytes();
        assert_eq!(raw_bytes.len(), WRAPPED_SEED_LEN);
        assert_eq!(&raw_bytes[..12], &iv);
        assert_eq!(&raw_bytes[12..76], &ciphertext);
        assert_eq!(&raw_bytes[76..92], &tag);

        let parsed = parse_wrapped_seed(&raw_bytes).expect("parse valid 92B blob");
        assert_eq!(parsed, blob);
        assert_eq!(parsed.to_vec(), raw_bytes.to_vec());

        let ct_and_tag = parsed.ciphertext_and_tag();
        assert_eq!(ct_and_tag.len(), AES_GCM_CIPHERTEXT_AND_TAG_LEN);
        assert_eq!(&ct_and_tag[..64], &ciphertext);
        assert_eq!(&ct_and_tag[64..80], &tag);

        let from_parts =
            WrappedSeedBlob::from_iv_and_encrypted(&iv, &ct_and_tag).expect("from parts");
        assert_eq!(from_parts, blob);
    }

